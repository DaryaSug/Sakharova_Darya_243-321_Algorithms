# Задание 1. Реализовать сортировку вставками по возрастанию.


n = int(input("Введите количество элементов N, не меньше 0: "))  

if n < 0:  
    print("Количество элементов не может быть отрицательным.")  
else:  
    numbers = []  
    for i in range(n): 
        value = float(input(f"Введите элемент {i + 1}: "))  
        numbers.append(value)  # Добавляем число в конец массива.

    print("Исходный массив:", numbers)  

    for i in range(1, n):  
        current = numbers[i]  # Сохраняем вставляемое число отдельно, чтобы не потерять его при сдвигах.
        j = i - 1  
        while j >= 0 and numbers[j] > current:  # Пока не вышли за левую границу и число слева больше вставляемого, продолжаем сдвиги.
            numbers[j + 1] = numbers[j]  # Передвигаем большее число на одну позицию вправо.
            j = j - 1  
        numbers[j + 1] = current  # Вставляем сохранённое число после последнего элемента, который не больше него.

    print("Массив по возрастанию:", numbers)  
