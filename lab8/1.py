# Задание 1. Реализовать сортировку вставками по возрастанию.
# Первый элемент считаем отсортированным, затем вставляем остальные в подходящие места слева.

n = int(input("Введите количество элементов N, не меньше 0: "))  # Вводим размер массива; ноль означает пустой массив.

if n < 0:  # Проверяем, не ввели ли отрицательное количество элементов.
    print("Количество элементов не может быть отрицательным.")  # Объясняем, почему такой размер не подходит.
else:  # Для допустимого размера вводим и сортируем массив.
    numbers = []  # Создаём пустой список для чисел.
    for i in range(n):  # По очереди вводим все N элементов.
        value = float(input(f"Введите элемент {i + 1}: "))  # Вводим очередное число, можно отрицательное или дробное.
        numbers.append(value)  # Добавляем число в конец массива.

    print("Исходный массив:", numbers)  # Показываем массив до сортировки.

    for i in range(1, n):  # Перебираем элементы со второго до последнего; слева уже находится отсортированная часть.
        current = numbers[i]  # Сохраняем вставляемое число отдельно, чтобы не потерять его при сдвигах.
        j = i - 1  # Начинаем сравнение с последнего элемента отсортированной части.
        while j >= 0 and numbers[j] > current:  # Пока не вышли за левую границу и число слева больше вставляемого, продолжаем сдвиги.
            numbers[j + 1] = numbers[j]  # Передвигаем большее число на одну позицию вправо.
            j = j - 1  # Переходим к следующему элементу слева.
        numbers[j + 1] = current  # Вставляем сохранённое число после последнего элемента, который не больше него.

    print("Массив по возрастанию:", numbers)  # Выводим отсортированный массив.
