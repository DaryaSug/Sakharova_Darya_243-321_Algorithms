# Задание 9. Найти номер последнего локального максимума массива.
# Элемент должен быть строго больше соседей; у крайнего элемента только один сосед.
# Единственный элемент массива считаем локальным максимумом. Если максимумов нет, выводим 0.

n = int(input("Введите положительный размер массива N: "))  
a = []  

for i in range(n):  
    value = float(input(f"Введите элемент A{i + 1}: ")) 
    a.append(value)  

number = 0  
for i in range(n - 1, -1, -1):  
    greater_left = i == 0 or a[i] > a[i - 1]  # Проверяем левого соседа, если он есть; or не вычисляет вторую часть, если первая уже истинна.
    greater_right = i == n - 1 or a[i] > a[i + 1]  # Проверяем правого соседа только тогда, когда он существует.
    if greater_left and greater_right:  # Элемент подходит, если он больше каждого существующего соседа.
        number = i + 1  # Превращаем индекс Python в номер элемента, начиная с 1.
        break  

print("Номер последнего локального максимума:", number)  
