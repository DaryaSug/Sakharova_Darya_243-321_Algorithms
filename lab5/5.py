# Задание 5. Сначала вывести элементы с нечётными номерами по возрастанию номеров,
# затем с чётными номерами по убыванию номеров. Нумерация в условии начинается с 1.

n = int(input("Введите положительный размер массива N: "))  # Вводим количество элементов.
a = []  # Создаём пустой исходный массив.

for i in range(n):  # Вводим каждый элемент массива отдельно.
    value = float(input(f"Введите элемент A{i + 1}: "))  # Читаем число с номером i+1.
    a.append(value)  # Добавляем его в конец массива.

result = []  # Подготавливаем список для элементов в новом порядке.

for i in range(0, n, 2):  # Индексы 0, 2, 4 соответствуют нечётным номерам 1, 3, 5.
    result.append(a[i])  # Добавляем элементы с нечётными номерами слева направо.

for i in range(n - 1, -1, -1):  # Перебираем индексы от последнего к первому.
    if (i + 1) % 2 == 0:  # Прибавляем 1 к индексу и проверяем, что номер элемента чётный.
        result.append(a[i])  # Добавляем элементы с чётными номерами справа налево.

print("Элементы в нужном порядке:", result)  # Выводим итоговую последовательность.
