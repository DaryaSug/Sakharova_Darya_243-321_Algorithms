# Задание 7. Проверить, образует ли целочисленный массив арифметическую прогрессию.
# По условию одинаковых чисел нет. Если прогрессия есть, вывести разность, иначе 0.

n = int(input("Введите положительный размер массива N: "))  # Вводим количество чисел.
a = []  # Создаём пустой массив целых чисел.

for i in range(n):  # По очереди вводим элементы массива.
    value = int(input(f"Введите целый элемент A{i + 1}: "))  # Вводим очередное целое число без повторений.
    a.append(value)  # Добавляем число в массив.

if n < 2:  # По одному элементу невозможно однозначно определить разность.
    print("Разность прогрессии:", 0)  # В этом случае выводим ноль.
else:  # Если есть хотя бы два элемента, проверяем их разности.
    difference = a[1] - a[0]  # Находим разность между вторым и первым элементами.
    is_progression = True  # Пока считаем, что массив является прогрессией.
    for i in range(2, n):  # Проверяем все пары соседних элементов, начиная со второго и третьего.
        if a[i] - a[i - 1] != difference:  # В прогрессии разности соседних элементов должны совпадать.
            is_progression = False  # Запоминаем, что нашли нарушение.
            break  # Останавливаем проверку, потому что результат уже известен.
    if is_progression:  # Если нарушений не нашли, массив является прогрессией.
        print("Разность прогрессии:", difference)  # Выводим общую разность.
    else:  # Если хотя бы одна разность отличается, прогрессии нет.
        print("Разность прогрессии:", 0)  # По условию в этом случае выводим ноль.
