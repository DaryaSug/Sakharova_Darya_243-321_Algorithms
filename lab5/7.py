# Задание 7. Проверить, образует ли целочисленный массив арифметическую прогрессию.
# По условию одинаковых чисел нет. Если прогрессия есть, вывести разность, иначе 0.

n = int(input("Введите положительный размер массива N: ")) 
a = []  

for i in range(n):  
    value = int(input(f"Введите целый элемент A{i + 1}: "))  
    a.append(value)  

if n < 2:  
    print("Разность прогрессии:", 0) 
else:  
    difference = a[1] - a[0]  # Находим разность между вторым и первым элементами.
    is_progression = True  # Пока считаем, что массив является прогрессией.
    for i in range(2, n): 
        if a[i] - a[i - 1] != difference: 
            is_progression = False  
            break 
    if is_progression:  # Если нарушений не нашли, массив является прогрессией.
        print("Разность прогрессии:", difference) 
    else: 
        print("Разность прогрессии:", 0) 
