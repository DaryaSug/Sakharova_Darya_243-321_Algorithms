# Задание 8. Найти минимум среди элементов с чётными номерами: A2, A4, A6 и так далее.
# Номера начинаются с 1, поэтому им соответствуют индексы 1, 3, 5 в Python.

n = int(input("Введите положительный размер массива N: "))  # Вводим количество элементов.
a = []  # Создаём пустой массив чисел.

for i in range(n):  # Вводим все элементы массива.
    value = float(input(f"Введите элемент A{i + 1}: "))  # Читаем очередное число.
    a.append(value)  # Сохраняем число в массиве.

if n < 2:  # Если элементов меньше двух, чётных номеров нет.
    print("В массиве нет элементов с чётными номерами.")  # Сообщаем, что минимум найти невозможно.
else:  # Иначе начинаем поиск со второго элемента.
    minimum = a[1]  # Пока считаем минимальным элемент с номером 2.
    for i in range(3, n, 2):  # Перебираем индексы 3, 5, 7, то есть номера 4, 6, 8.
        if a[i] < minimum:  # Проверяем, меньше ли очередной элемент текущего минимума.
            minimum = a[i]  # Запоминаем новое наименьшее значение.
    print("Минимум среди элементов с чётными номерами:", minimum)  # Выводим найденный минимум.
