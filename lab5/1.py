# Задание 1. Сформировать массив из N первых положительных нечётных чисел, N > 0.

n = int(input("Введите целое число N больше 0: "))  # Вводим количество элементов массива.
numbers = []  # Создаём пустой список, в который будем добавлять числа.

for i in range(n):  # Повторяем добавление N раз; i принимает значения от 0 до N-1.
    number = 2 * i + 1  # Получаем очередное нечётное число: 1, 3, 5 и так далее.
    numbers.append(number)  # Добавляем полученное число в конец массива.

print("Массив:", numbers)  # Выводим все N нечётных чисел.
