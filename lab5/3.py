# Задание 3. Сформировать целочисленный массив из N элементов, N > 2.
# Первые элементы равны A и B, каждый следующий равен сумме всех предыдущих.

n = int(input("Введите целое число N больше 2: "))  
a = int(input("Введите первый элемент A: "))  
b = int(input("Введите второй элемент B: "))  
numbers = [a, b]  
total = a + b  

for i in range(2, n):  
    numbers.append(total)  # Новый элемент равен сумме всех предыдущих.
    total = total + numbers[-1]  # Прибавляем только что добавленный элемент к общей сумме.

print("Массив:", numbers)  
