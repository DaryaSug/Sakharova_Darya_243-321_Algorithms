# Задание 3. Сформировать целочисленный массив из N элементов, N > 2.
# Первые элементы равны A и B, каждый следующий равен сумме всех предыдущих.

n = int(input("Введите целое число N больше 2: "))  # Вводим нужный размер массива.
a = int(input("Введите первый элемент A: "))  # Вводим первое целое число.
b = int(input("Введите второй элемент B: "))  # Вводим второе целое число.
numbers = [a, b]  # Создаём массив с двумя уже известными элементами.
total = a + b  # Запоминаем сумму всех элементов, которые сейчас находятся в массиве.

for i in range(2, n):  # Добавляем элементы с третьего по N-й; индексы начинаются с 0.
    numbers.append(total)  # Новый элемент равен сумме всех предыдущих.
    total = total + numbers[-1]  # Прибавляем только что добавленный элемент к общей сумме.

print("Массив:", numbers)  # Выводим готовый массив.
