# Задание 4. Вывести элементы в порядке: A1, AN, A2, A(N-1) и так далее.
# Если размер нечётный, средний элемент выводится один раз.

n = int(input("Введите положительный размер массива N: "))  # Вводим количество элементов.
a = []  # Создаём пустой массив для исходных чисел.

for i in range(n):  # По очереди вводим N элементов.
    value = float(input(f"Введите элемент A{i + 1}: "))  # В приглашении показываем номер элемента, начиная с 1.
    a.append(value)  # Добавляем введённое число в массив.

result = []  # Здесь соберём элементы в требуемом порядке.
left = 0  # Начинаем с индекса первого элемента.
right = n - 1  # Запоминаем индекс последнего элемента.

while left <= right:  # Продолжаем, пока не обработали все элементы между границами.
    result.append(a[left])  # Сначала берём элемент с левого края.
    if left < right:  # Проверяем, что справа находится другой элемент, а не тот же самый средний.
        result.append(a[right])  # Затем берём элемент с правого края.
    left = left + 1  # Сдвигаем левую границу на один элемент вправо.
    right = right - 1  # Сдвигаем правую границу на один элемент влево.

print("Элементы в нужном порядке:", result)  # Выводим полученную последовательность.
