# Задание 6. Найти среднее арифметическое элементов с номерами от K до L включительно.
# По условию 1 <= K <= L <= N; номера элементов начинаются с 1.

n = int(input("Введите положительный размер массива N: "))  # Вводим количество элементов.
a = []  # Создаём пустой массив для чисел.

for i in range(n):  # Вводим все N элементов.
    value = float(input(f"Введите элемент A{i + 1}: "))  # Вводим очередное число, можно дробное.
    a.append(value)  # Сохраняем число в массиве.

k = int(input("Введите номер первого элемента K: "))  # Вводим начало выбранного участка.
l = int(input("Введите номер последнего элемента L: "))  # Вводим конец выбранного участка.

if not 1 <= k <= l <= n:  # Проверяем порядок номеров и границы массива.
    print("Номера должны удовлетворять условию 1 <= K <= L <= N.")  # Сообщаем о неверных границах.
else:  # Для допустимых номеров вычисляем среднее.
    total = 0  # Начинаем накапливать сумму с нуля.
    for i in range(k - 1, l):  # Переходим от номеров к индексам и включаем элемент с номером L.
        total = total + a[i]  # Прибавляем очередной элемент выбранного участка.
    average = total / (l - k + 1)  # Делим сумму на количество элементов от K до L.
    print("Среднее арифметическое:", average)  # Показываем найденное среднее.
