# Задание 6. Найти среднее арифметическое элементов с номерами от K до L включительно.
# По условию 1 <= K <= L <= N; номера элементов начинаются с 1.

n = int(input("Введите положительный размер массива N: ")) 
a = []  

for i in range(n):  
    value = float(input(f"Введите элемент A{i + 1}: ")) 
    a.append(value)  

k = int(input("Введите номер первого элемента K: "))  
l = int(input("Введите номер последнего элемента L: "))  

if not 1 <= k <= l <= n:  
    print("Номера должны удовлетворять условию 1 <= K <= L <= N.")  # Сообщаем о неверных границах.
else:  # Для допустимых номеров вычисляем среднее.
    total = 0  # Начинаем накапливать сумму с нуля.
    for i in range(k - 1, l):  # Переходим от номеров к индексам и включаем элемент с номером L.
        total = total + a[i]  # Прибавляем очередной элемент выбранного участка.
    average = total / (l - k + 1)  # Делим сумму на количество элементов от K до L.
    print("Среднее арифметическое:", average)  
