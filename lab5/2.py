# Задание 2. Сформировать массив из N первых членов геометрической прогрессии, N > 1.
# A — первый член, D — число, на которое умножают предыдущий член для получения следующего.

n = int(input("Введите целое число N больше 1: ")) 
a = float(input("Введите первый член A: "))  
d = float(input("Введите знаменатель D: "))  
numbers = []  
current = a  

for i in range(n):  
    numbers.append(current)  # Сохраняем текущий член прогрессии в массиве.
    current = current * d  # Умножаем текущий член на D и получаем следующий.

print("Массив:", numbers) 
