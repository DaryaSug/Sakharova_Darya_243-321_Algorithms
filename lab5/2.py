# Задание 2. Сформировать массив из N первых членов геометрической прогрессии, N > 1.
# A — первый член, D — число, на которое умножают предыдущий член для получения следующего.

n = int(input("Введите целое число N больше 1: "))  # Вводим количество членов прогрессии.
a = float(input("Введите первый член A: "))  # Вводим первое число прогрессии.
d = float(input("Введите знаменатель D: "))  # Вводим множитель для перехода к следующему числу.
numbers = []  # Создаём пустой массив для членов прогрессии.
current = a  # Первым в массив должен попасть член A.

for i in range(n):  # Повторяем добавление N раз.
    numbers.append(current)  # Сохраняем текущий член прогрессии в массиве.
    current = current * d  # Умножаем текущий член на D и получаем следующий.

print("Массив:", numbers)  # Выводим построенную геометрическую прогрессию.
