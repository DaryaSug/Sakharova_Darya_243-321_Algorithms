# Задание 10. В целочисленном массиве ровно два одинаковых элемента.
# Найти их номера и вывести по возрастанию; номера начинаются с 1.

n = int(input("Введите размер массива N не меньше 2: "))  # Вводим количество элементов.
a = []  # Создаём пустой массив целых чисел.

for i in range(n):  # Вводим все элементы массива.
    value = int(input(f"Введите целый элемент A{i + 1}: "))  # Читаем очередное целое число.
    a.append(value)  # Сохраняем число в массиве.

found = False  # Запоминаем, что пару одинаковых элементов пока не нашли.

for i in range(n - 1):  # Выбираем первый элемент каждой возможной пары.
    for j in range(i + 1, n):  # Второй элемент берём только правее первого, чтобы номера шли по возрастанию.
        if a[i] == a[j]:  # Проверяем, совпадают ли значения выбранных элементов.
            print("Номера одинаковых элементов:", i + 1, j + 1)  # Выводим номера вместо индексов Python.
            found = True  # Отмечаем, что нужная пара найдена.
            break  # Завершаем внутренний цикл.
    if found:  # Проверяем, нашли ли пару во внутреннем цикле.
        break  # Завершаем и внешний цикл, потому что по условию пара только одна.

if not found:  # Этот случай возможен, если введённый массив не соответствует условию.
    print("Одинаковых элементов не найдено.")  # Сообщаем об отсутствии пары.
