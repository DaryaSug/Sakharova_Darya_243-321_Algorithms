# Задание 8. Даны точки A, B, C на числовой оси.
# Точка C расположена между A и B. Найти произведение длин AC и BC.

a = float(input("Введите координату точки A: "))  
b = float(input("Введите координату точки B: "))  
c = float(input("Введите координату точки C между A и B: "))  

ac = abs(c - a)  # Находим длину,модуль разности координат.
bc = abs(c - b)  
product = ac * bc  # Умножаем две длины

print("Произведение длин AC и BC:", product)  # Показываем произведение длин.
