# Задание 8. Даны точки A, B, C на числовой оси.
# Точка C расположена между A и B. Найти произведение длин AC и BC.

a = float(input("Введите координату точки A: "))  # Вводим положение точки A на числовой оси.
b = float(input("Введите координату точки B: "))  # Вводим положение точки B.
c = float(input("Введите координату точки C между A и B: "))  # Вводим координату C, которая по условию лежит между A и B.

ac = abs(c - a)  # Находим длину AC: модуль разности координат.
bc = abs(c - b)  # Находим длину BC тем же способом.
product = ac * bc  # Умножаем две длины и сохраняем результат.

print("Произведение длин AC и BC:", product)  # Показываем произведение длин.
