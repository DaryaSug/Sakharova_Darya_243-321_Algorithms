# Задание 6. Найти расстояние между точками (x1, y1) и (x2, y2).

from math import sqrt  # Подключаем sqrt — функцию для вычисления квадратного корня.

x1 = float(input("Введите x1: "))  # Вводим координату x первой точки.
y1 = float(input("Введите y1: "))  # Вводим координату y первой точки.
x2 = float(input("Введите x2: "))  # Вводим координату x второй точки.
y2 = float(input("Введите y2: "))  # Вводим координату y второй точки.

distance = sqrt((x2 - x1) ** 2 + (y2 - y1) ** 2)  # Складываем квадраты разностей координат и берём корень.

print("Расстояние между точками:", distance)  # Показываем найденное расстояние.
