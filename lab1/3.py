# Задание 3. Даны два числа a и b. Найти их среднее арифметическое.

a = float(input("Введите число a: "))  # Вводим первое число; оно может быть дробным.
b = float(input("Введите число b: "))  # Вводим второе число и сохраняем его в b.

average = (a + b) / 2  # Складываем числа и делим сумму на 2 — получаем среднее.

print("Среднее арифметическое:", average)  # Показываем результат на экране.
