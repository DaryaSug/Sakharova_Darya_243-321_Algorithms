# Задание 9. Даны противоположные вершины прямоугольника.
# Стороны параллельны осям координат. Найти периметр и площадь.

x1 = float(input("Введите x1: "))  
y1 = float(input("Введите y1: "))  
x2 = float(input("Введите x2: "))  
y2 = float(input("Введите y2: "))  

a = abs(x2 - x1)  # Разница координат x по модулю даёт горизонтальную сторону.
b = abs(y2 - y1)  # Разница координат y по модулю даёт вертикальную сторону.
p = 2 * (a + b)  
s = a * b  

print("Периметр прямоугольника:", p)  
print("Площадь прямоугольника:", s)  
