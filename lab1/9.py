# Задание 9. Даны противоположные вершины прямоугольника.
# Стороны параллельны осям координат. Найти периметр и площадь.

x1 = float(input("Введите x1: "))  # Вводим координату x первой вершины прямоугольника.
y1 = float(input("Введите y1: "))  # Вводим координату y первой вершины.
x2 = float(input("Введите x2: "))  # Вводим координату x противоположной вершины.
y2 = float(input("Введите y2: "))  # Вводим координату y противоположной вершины.

a = abs(x2 - x1)  # Разница координат x по модулю даёт горизонтальную сторону.
b = abs(y2 - y1)  # Разница координат y по модулю даёт вертикальную сторону.
p = 2 * (a + b)  # Складываем две соседние стороны и умножаем на 2 — это периметр.
s = a * b  # Умножаем стороны и получаем площадь.

print("Периметр прямоугольника:", p)  # Выводим периметр.
print("Площадь прямоугольника:", s)  # Выводим площадь.
