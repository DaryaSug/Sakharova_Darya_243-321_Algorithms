# Задание 12. Найти y = 4*(x-3)^6 - 7*(x-3)^3 + 2 при данном x.

x = float(input("Введите x: "))  # Вводим x и превращаем ответ в число, которое может быть дробным.

t = x - 3  # Вычисляем x минус 3 и сохраняем в t, чтобы не повторять вычитание.
y = 4 * t ** 6 - 7 * t ** 3 + 2  # Считаем формулу: ** 6 — шестая степень, ** 3 — куб.

print("Значение функции y:", y)  # Выводим вычисленное значение y.
