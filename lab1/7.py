# Задание 7. Даны точки A, B, C на числовой оси.
# Найти длины отрезков AC и BC и их сумму.

a = float(input("Введите координату точки A: "))  
b = float(input("Введите координату точки B: "))  
c = float(input("Введите координату точки C: ")) 

ac = abs(c - a)  # Находим расстояние от A до C, abs убирает возможный минус.
bc = abs(c - b)  

print("Длина AC:", ac)  
print("Длина BC:", bc)  
print("Сумма длин AC и BC:", ac + bc) 
