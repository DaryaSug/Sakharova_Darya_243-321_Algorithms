# Задание 7. Даны точки A, B, C на числовой оси.
# Найти длины отрезков AC и BC и их сумму.

a = float(input("Введите координату точки A: "))  # Вводим положение точки A на числовой оси.
b = float(input("Введите координату точки B: "))  # Вводим положение точки B.
c = float(input("Введите координату точки C: "))  # Вводим положение точки C.

ac = abs(c - a)  # Находим расстояние от A до C; abs убирает возможный минус.
bc = abs(c - b)  # Находим расстояние от B до C тем же способом.

print("Длина AC:", ac)  # Показываем длину отрезка AC.
print("Длина BC:", bc)  # Показываем длину отрезка BC.
print("Сумма длин AC и BC:", ac + bc)  # Складываем длины и показываем сумму.
