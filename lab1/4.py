# Задание 4. Даны два ненулевых числа.
# Найти сумму, разность, произведение и частное их квадратов.

a = float(input("Введите ненулевое число a: "))  # Вводим первое число, не равное нулю.
b = float(input("Введите ненулевое число b: "))  # Вводим второе число, не равное нулю.

a_squared = a ** 2  # Возводим a в квадрат: умножаем a само на себя.
b_squared = b ** 2  # Возводим b в квадрат; ** обозначает возведение в степень.

print("Сумма квадратов:", a_squared + b_squared)  # Складываем квадраты и выводим ответ.
print("Разность квадратов:", a_squared - b_squared)  # Из квадрата a вычитаем квадрат b.
print("Произведение квадратов:", a_squared * b_squared)  # Умножаем квадраты и выводим ответ.
print("Частное квадратов:", a_squared / b_squared)  # Делим квадрат a на квадрат b и выводим ответ.
