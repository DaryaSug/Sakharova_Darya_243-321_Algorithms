# Задание 2. Дан диаметр окружности d. Найти длину L = pi * d.
# По условию pi = 3.14.

d = float(input("Введите диаметр окружности: "))  # Вводим диаметр и превращаем ответ в число.

length = 3.14 * d  # Умножаем диаметр на 3.14 и сохраняем длину окружности.

print("Длина окружности:", length)  # Выводим найденную длину на экран.
