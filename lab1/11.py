# Задание 11. Найти y = 3*x^6 - 6*x^2 - 7 при данном x.
# В Python возведение в степень записывается через **.

x = float(input("Введите x: "))  # Вводим x и превращаем ответ в число, которое может быть дробным.

y = 3 * x ** 6 - 6 * x ** 2 - 7  # Подставляем x в формулу: ** 6 — шестая степень, ** 2 — квадрат.

print("Значение функции y:", y)  # Выводим вычисленное значение y.
