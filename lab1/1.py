# Задание 1. Даны стороны прямоугольника a и b.
# Найти площадь S = a * b и периметр P = 2 * (a + b).

a = float(input("Введите сторону a: "))  # Просим ввести сторону a и превращаем ответ в число.
b = float(input("Введите сторону b: "))  # Так же вводим сторону b; float позволяет вводить дроби.

s = a * b  # Умножаем стороны и сохраняем площадь в переменной s.
p = 2 * (a + b)  # Складываем стороны и умножаем на 2, чтобы получить периметр.

print("Площадь прямоугольника:", s)  # Показываем площадь на экране.
print("Периметр прямоугольника:", p)  # Показываем периметр на экране.
