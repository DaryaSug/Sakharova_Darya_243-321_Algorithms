# Задание 5. Даны два ненулевых числа.
# Найти сумму, разность, произведение и частное их модулей.

a = float(input("Введите ненулевое число a: "))  # Вводим первое число, не равное нулю.
b = float(input("Введите ненулевое число b: "))  # Вводим второе число, не равное нулю.

a_abs = abs(a)  # Получаем модуль a: например, abs(-3) равно 3.
b_abs = abs(b)  # Получаем модуль b — расстояние от числа b до нуля.

print("Сумма модулей:", a_abs + b_abs)  # Складываем модули и выводим ответ.
print("Разность модулей:", a_abs - b_abs)  # Из модуля a вычитаем модуль b.
print("Произведение модулей:", a_abs * b_abs)  # Умножаем модули и выводим ответ.
print("Частное модулей:", a_abs / b_abs)  # Делим модуль a на модуль b и выводим ответ.
