# Задание 10. Даны координаты трех вершин треугольника.
# Найти периметр и площадь.

from math import sqrt  # Подключаем функцию sqrt для вычисления квадратного корня.

x1 = float(input("Введите x1: "))  
y1 = float(input("Введите y1: "))  
x2 = float(input("Введите x2: "))  
y2 = float(input("Введите y2: "))  
x3 = float(input("Введите x3: "))  
y3 = float(input("Введите y3: "))  

ab = sqrt((x2 - x1) ** 2 + (y2 - y1) ** 2)  # Находим длину сторон: корень из суммы квадратов разностей координат.
bc = sqrt((x3 - x2) ** 2 + (y3 - y2) ** 2)  
ca = sqrt((x1 - x3) ** 2 + (y1 - y3) ** 2)  
p = ab + bc + ca 

s = abs((x2 - x1) * (y3 - y1) - (x3 - x1) * (y2 - y1)) / 2  # Считаем разность произведений, берём модуль и делим на 2.

print("Периметр треугольника:", p) 
print("Площадь треугольника:", s) 
