# Задание 10. Даны координаты трех вершин треугольника.
# Найти периметр и площадь.

from math import sqrt  # Подключаем функцию sqrt для вычисления квадратного корня.

x1 = float(input("Введите x1: "))  # Вводим координату x вершины A.
y1 = float(input("Введите y1: "))  # Вводим координату y вершины A.
x2 = float(input("Введите x2: "))  # Вводим координату x вершины B.
y2 = float(input("Введите y2: "))  # Вводим координату y вершины B.
x3 = float(input("Введите x3: "))  # Вводим координату x вершины C.
y3 = float(input("Введите y3: "))  # Вводим координату y вершины C.

ab = sqrt((x2 - x1) ** 2 + (y2 - y1) ** 2)  # Находим длину AB: корень из суммы квадратов разностей координат.
bc = sqrt((x3 - x2) ** 2 + (y3 - y2) ** 2)  # По той же формуле находим длину BC.
ca = sqrt((x1 - x3) ** 2 + (y1 - y3) ** 2)  # По той же формуле находим длину CA.
p = ab + bc + ca  # Складываем три стороны и получаем периметр.

# Формула ниже даёт площадь по координатам трёх вершин.
# abs берёт модуль, поэтому порядок вершин не меняет знак площади.
s = abs((x2 - x1) * (y3 - y1) - (x3 - x1) * (y2 - y1)) / 2  # Считаем разность произведений, берём модуль и делим на 2.

print("Периметр треугольника:", p)  # Показываем сумму длин сторон.
print("Площадь треугольника:", s)  # Показываем найденную площадь.
