# Задание 1. Реализовать сортировку выбором по возрастанию.
# На каждом шаге находим минимум оставшейся части и ставим его на первое место этой части.

n = int(input("Введите количество элементов N, не меньше 0: "))  # Вводим размер массива; ноль означает пустой массив.

if n < 0:  # Проверяем, не ввели ли отрицательное количество элементов.
    print("Количество элементов не может быть отрицательным.")  # Объясняем, почему такой размер не подходит.
else:  # Для допустимого размера вводим и сортируем массив.
    numbers = []  # Создаём пустой список для чисел.
    for i in range(n):  # По очереди вводим все N элементов.
        value = float(input(f"Введите элемент {i + 1}: "))  # Вводим очередное число, можно отрицательное или дробное.
        numbers.append(value)  # Добавляем число в конец массива.

    print("Исходный массив:", numbers)  # Показываем массив до сортировки.

    for i in range(n - 1):  # Перебираем позиции от первой до предпоследней; часть слева уже отсортирована.
        min_index = i  # Пока считаем текущий элемент наименьшим в оставшейся части.
        for j in range(i + 1, n):  # Просматриваем все элементы правее текущей позиции.
            if numbers[j] < numbers[min_index]:  # Проверяем, нашли ли число меньше запомненного минимума.
                min_index = j  # Запоминаем индекс нового наименьшего элемента.
        if min_index != i:  # Проверяем, нужно ли переносить найденный минимум на текущую позицию.
            numbers[i], numbers[min_index] = numbers[min_index], numbers[i]  # Меняем текущий элемент и минимум местами.

    print("Массив по возрастанию:", numbers)  # Выводим отсортированный массив.
