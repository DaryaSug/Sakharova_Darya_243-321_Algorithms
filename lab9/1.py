# Задание 1. Реализовать сортировку выбором по возрастанию.
# На каждом шаге находим минимум оставшейся части и ставим его на первое место этой части.

n = int(input("Введите количество элементов N, не меньше 0: ")) 

if n < 0:  
    print("Количество элементов не может быть отрицательным.")  
else:  
    numbers = []  
    for i in range(n): 
        value = float(input(f"Введите элемент {i + 1}: "))  
        numbers.append(value)  # Добавляем число в конец массива.

    print("Исходный массив:", numbers)  

    for i in range(n - 1):  
        min_index = i  # Пока считаем текущий элемент наименьшим в оставшейся части.
        for j in range(i + 1, n):  # Просматриваем все элементы правее текущей позиции.
            if numbers[j] < numbers[min_index]:  # Проверяем, нашли ли число меньше запомненного минимума.
                min_index = j  # Запоминаем индекс нового наименьшего элемента.
        if min_index != i:  # Проверяем, нужно ли переносить найденный минимум на текущую позицию.
            numbers[i], numbers[min_index] = numbers[min_index], numbers[i]  

    print("Массив по возрастанию:", numbers)  
