# Задание 5. Рекурсивно найти элемент в отсортированном массиве бинарным поиском.
# Числа должны идти от меньшего к большему; одинаковые значения допустимы.

def binary_search(numbers, target, left, right):  # Передаём массив, искомое число и границы поиска.
    if left > right:  # Если левая граница прошла правую, область поиска стала пустой.
        return -1  # Значение -1 означает, что элемент не найден.
    middle = (left + right) // 2  # Находим индекс среднего элемента текущего участка.
    if numbers[middle] == target:  # Сравниваем средний элемент с искомым числом.
        return middle  # Если числа совпали, возвращаем индекс найденного элемента.
    if target < numbers[middle]:  # Меньшее число может находиться только левее середины.
        return binary_search(numbers, target, left, middle - 1)  # Рекурсивно ищем в левой половине.
    return binary_search(numbers, target, middle + 1, right)  # В остальных случаях ищем в правой половине.


numbers = list(map(int, input("Введите целые числа от меньшего к большему через пробел: ").split()))  # Разделяем ввод по пробелам и превращаем части в список чисел.
target = int(input("Введите число для поиска: "))  # Вводим искомое целое число.
index = binary_search(numbers, target, 0, len(numbers) - 1)  # Начинаем поиск во всём массиве.

if index == -1:  # Проверяем, сообщила ли функция об отсутствии числа.
    print("Элемент не найден.")  # Сообщаем, что такого числа в массиве нет.
else:  # Если индекс не равен -1, поиск завершился успешно.
    print("Индекс найденного элемента, считая с 0:", index)  # Выводим индекс; первый элемент имеет индекс 0.
