# Задание 4. Рекурсивно проверить, является ли строка палиндромом.
# Палиндром одинаково читается с двух сторон; здесь учитываются регистр, пробелы и знаки.

def is_palindrome(text):  # Создаём функцию, которая возвращает True или False.
    if len(text) <= 1:  # Пустая строка и один символ одинаковы при чтении с двух сторон.
        return True  # Базовый случай: строка является палиндромом.
    if text[0] != text[-1]:  # Сравниваем первый и последний символы.
        return False  # Если они различаются, вся строка не может быть палиндромом.
    return is_palindrome(text[1:-1])  # Убираем крайние символы и рекурсивно проверяем середину.


text = input("Введите строку: ")  # Вводим строку для проверки.

if is_palindrome(text):  # Проверяем ответ рекурсивной функции.
    print("Строка является палиндромом.")  # Сообщаем, что строка читается одинаково с двух сторон.
else:  # Сюда попадаем, если функция вернула False.
    print("Строка не является палиндромом.")  # Сообщаем, что строка не прошла проверку.
