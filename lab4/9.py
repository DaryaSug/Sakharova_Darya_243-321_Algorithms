# Задание 9. Решить головоломку «Ханойская башня» с помощью рекурсии.
# Все диски нужно перенести с A на C, используя B; больший диск нельзя класть на меньший.
# Диск 1 — самый маленький, диск n — самый большой.

def hanoi(n, source, target, spare):  
    if n == 0:  
        return  
    hanoi(n - 1, source, spare, target)  # Рекурсивно переносим верхние n-1 дисков на вспомогательный стержень.
    print("Переместить диск", n, "со стержня", source, "на стержень", target)  # Переносим самый большой из оставшихся дисков.
    hanoi(n - 1, spare, target, source)  # Рекурсивно переносим меньшие диски на конечный стержень поверх большого.


n = int(input("Введите положительное количество дисков: "))  

if n <= 0:  
    print("Количество дисков должно быть больше 0.")  
else:  
    hanoi(n, "A", "C", "B")  # Переносим башню со стержня A на C с помощью стержня B.
