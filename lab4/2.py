# Задание 2. Рекурсивно вычислить n-е число Фибоначчи.
# Используем нумерацию F(0) = 0, F(1) = 1; каждое следующее число — сумма двух предыдущих.

from functools import lru_cache  # Подключаем средство для сохранения уже вычисленных результатов.


@lru_cache(maxsize=None)  # Запоминаем ответы функции, чтобы не вычислять одно и то же заново.
def fibonacci(n):  # Создаём функцию для нахождения числа Фибоначчи с номером n.
    if n <= 1:  # Базовые случаи — номера 0 и 1.
        return n  # Для этих номеров ответ совпадает с самим номером.
    return fibonacci(n - 1) + fibonacci(n - 2)  # Рекурсивно находим два предыдущих числа и складываем их.


n = int(input("Введите целый номер n, начиная с 0: "))  # Вводим номер нужного числа Фибоначчи.

if n < 0:  # Проверяем, не оказался ли номер отрицательным.
    print("Номер должен быть неотрицательным.")  # Сообщаем о недопустимом номере.
else:  # Для допустимого номера вычисляем результат.
    print("Число Фибоначчи:", fibonacci(n))  # Выводим найденное число.
