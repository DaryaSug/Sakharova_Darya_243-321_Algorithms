# Задание 1. Рекурсивно вычислить факториал числа n.
# Факториал — произведение целых чисел от 1 до n; факториал нуля равен 1.

def factorial(n):  
    if n == 0:  
        return 1  
    return n * factorial(n - 1)  # Умножаем n на факториал предыдущего числа.


n = int(input("Введите целое неотрицательное число n: ")) 

if n < 0:  
    print("Факториал в этом задании определён только для неотрицательных чисел.")  
else:  
    print("Факториал:", factorial(n))  