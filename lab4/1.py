# Задание 1. Рекурсивно вычислить факториал числа n.
# Факториал — произведение целых чисел от 1 до n; факториал нуля равен 1.

def factorial(n):  # Создаём функцию, которая вычисляет факториал.
    if n == 0:  # Базовый случай: дошли до нуля и дальше вызывать функцию не нужно.
        return 1  # Возвращаем известное значение факториала нуля.
    return n * factorial(n - 1)  # Умножаем n на факториал предыдущего числа.


n = int(input("Введите целое неотрицательное число n: "))  # Вводим число, факториал которого нужно найти.

if n < 0:  # Проверяем, не ввели ли отрицательное число.
    print("Факториал в этом задании определён только для неотрицательных чисел.")  # Объясняем, почему вычисление невозможно.
else:  # Для нуля и положительных чисел запускаем вычисление.
    print("Факториал:", factorial(n))  # Вызываем рекурсивную функцию и выводим её результат.
