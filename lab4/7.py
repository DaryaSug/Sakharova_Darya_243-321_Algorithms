# Задание 7. Рекурсивно разложить целое число на сумму простых чисел.
# Выводим один возможный вариант; простые слагаемые могут повторяться.

def is_prime(number):  # функция для проверки простого числа.
    if number < 2:  # Числа меньше 2 не являются простыми.
        return False  
    divisor = 2  # Начинаем искать делители с числа 2.
    while divisor * divisor <= number:  # Достаточно проверять делители до квадратного корня включительно.
        if number % divisor == 0:  # Проверяем, делится ли число на divisor без остатка.
            return False  # Найден дополнительный делитель, поэтому число не простое.
        divisor = divisor + 1  # Переходим к следующему возможному делителю.
    return True  # Если делителей не нашли, число простое.


def prime_sum(number):  
    if number == 0: 
        return [] 
    if number < 2:  
        return None  # Значение None означает, что этот вариант не подошёл.
    for candidate in range(2, number + 1):  # Перебираем возможные слагаемые, начиная с наименьшего простого числа.
        if is_prime(candidate):  # Используем в сумме только простые числа.
            rest = prime_sum(number - candidate)  # Рекурсивно раскладываем оставшуюся часть числа.
            if rest is not None:  # Проверяем, удалось ли разложить остаток.
                return [candidate] + rest  # Добавляем выбранное простое число к найденным слагаемым.
    return None  # Если ни один вариант не подошёл, сообщаем об отсутствии разложения.


number = int(input("Введите целое число не меньше 2: "))  

if number < 2: 
    print("Нужно ввести целое число не меньше 2.")  
else:  
    result = prime_sum(number)  # Запускаем рекурсивную функцию и получаем список слагаемых.
    print(number, "=", " + ".join(map(str, result)))  # Превращаем слагаемые в текст и соединяем знаками плюса.
