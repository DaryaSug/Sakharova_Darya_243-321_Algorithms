# Задание 6. Рекурсивно изменить порядок слов строки на обратный.
# Между словами в результате будет по одному пробелу.

def reverse_words(text):  
    parts = text.split(maxsplit=1)  # Отделяем первое слово от оставшейся части строки.
    if len(parts) <= 1: 
        return " ".join(parts)  # Возвращаем оставшееся слово либо пустую строку.
    return reverse_words(parts[1]) + " " + parts[0]  # Переворачиваем оставшиеся слова и переносим первое слово в конец.


text = input("Введите строку: ") 
print("Обратный порядок слов:", reverse_words(text))  
