# Задание 8. Рекурсивно подсчитать количество цифр целого числа.
# Знак минус не считается цифрой; в числе 0 одна цифра.

def count_digits(number):  # Создаём функцию, которая считает цифры числа.
    number = abs(number)  # Убираем минус, если число отрицательное.
    if number < 10:  # Базовый случай: осталось число из одной цифры, включая ноль.
        return 1  # Возвращаем количество цифр в таком числе.
    return 1 + count_digits(number // 10)  # Убираем последнюю цифру и прибавляем 1 к числу оставшихся цифр.


number = int(input("Введите целое число: "))  # Вводим положительное число, отрицательное число или ноль.
print("Количество цифр:", count_digits(number))  # Вызываем функцию и показываем найденное количество.
