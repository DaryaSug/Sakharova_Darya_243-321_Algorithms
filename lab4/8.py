# Задание 8. Рекурсивно подсчитать количество цифр целого числа.
# Знак минус не считается цифрой; в числе 0 одна цифра.

def count_digits(number):  
    number = abs(number) 
    if number < 10:  
        return 1  
    return 1 + count_digits(number // 10)  # Убираем последнюю цифру и прибавляем 1 к числу оставшихся цифр.


number = int(input("Введите целое число: "))  # Вводим положительное число, отрицательное число или ноль.
print("Количество цифр:", count_digits(number))  
