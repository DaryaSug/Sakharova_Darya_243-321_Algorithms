# Задание 3. Рекурсивно возвести число x в целую степень n.
# Поддерживаются нулевая, положительные и отрицательные степени.

def power(x, n):  # Создаём функцию для вычисления x в степени n.
    if n == 0:  # Базовый случай: нулевая степень равна 1.
        return 1  # Завершаем рекурсию и возвращаем единицу.
    if n < 0:  # Для отрицательной степени нужен обратный результат.
        return 1 / power(x, -n)  # Например, x в степени -2 равно 1, делённому на x в степени 2.
    half = power(x, n // 2)  # Рекурсивно вычисляем степень с вдвое меньшим показателем.
    if n % 2 == 0:  # Проверяем, является ли показатель чётным.
        return half * half  # Для чётного показателя перемножаем две одинаковые половины.
    return x * half * half  # Для нечётного показателя дополнительно умножаем на x.


x = float(input("Введите число x: "))  # Вводим основание степени, можно дробное.
n = int(input("Введите целую степень n: "))  # Вводим показатель степени.

if x == 0 and n < 0:  # Ноль в отрицательной степени потребовал бы деления на ноль.
    print("Нельзя возвести ноль в отрицательную степень.")  # Объясняем невозможность такого вычисления.
else:  # Для остальных значений вызываем функцию.
    print("Результат:", power(x, n))  # Выводим вычисленную степень.
