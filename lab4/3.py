# Задание 3. Рекурсивно возвести число x в целую степень n.
# Поддерживаются нулевая, положительные и отрицательные степени.

def power(x, n):  
    if n == 0: 
        return 1 
    if n < 0:  
        return 1 / power(x, -n)  
    half = power(x, n // 2) 
    if n % 2 == 0:  # Проверяем, является ли показатель чётным.
        return half * half  # Для чётного показателя перемножаем две одинаковые половины.
    return x * half * half  # Для нечётного показателя дополнительно умножаем на x.


x = float(input("Введите число x: ")) 
n = int(input("Введите целую степень n: ")) 

if x == 0 and n < 0: 
    print("Нельзя возвести ноль в отрицательную степень.") 
else:  
    print("Результат:", power(x, n))  
