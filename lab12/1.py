# Задание 1. Реализовать основные операции с очередью.
# Очередь работает по правилу FIFO: кто первым добавлен, тот первым извлекается.

from collections import deque  # Подключаем deque — готовую структуру для добавления и удаления с обоих концов.

queue = deque()  # Создаём пустую очередь; добавлять будем справа, а извлекать слева.

print("Работа с очередью:")  # Выводим заголовок программы.
print("1 — Добавить элемент")  # Показываем команду добавления в конец очереди.
print("2 — Извлечь первый элемент")  # Показываем команду удаления из начала очереди.
print("3 — Посмотреть первый элемент без удаления")  # Показываем команду просмотра начала очереди.
print("4 — Проверить, пуста ли очередь")  # Показываем команду проверки пустоты.
print("5 — Узнать размер очереди")  # Показываем команду подсчёта элементов.
print("6 — Проверить наличие элемента")  # Показываем команду поиска значения.
print("7 — Очистить очередь")  # Показываем команду удаления всех элементов.
print("8 — Вывести все элементы")  # Показываем команду просмотра очереди целиком.
print("0 — Завершить работу")  # Показываем команду выхода из программы.

while True:  # Повторяем выбор действий, пока пользователь не выберет выход.
    choice = input("Выберите пункт меню: ").strip()  # Читаем номер команды как текст и убираем случайные пробелы по краям.

    if choice == "1":  # Если выбрано добавление, запрашиваем новое значение.
        item = input("Введите элемент очереди: ")  # Сохраняем ввод как текст: можно вводить слова или числа.
        queue.append(item)  # Добавляем элемент в конец очереди.
        print("Добавлен элемент:", item)  # Подтверждаем добавление.

    elif choice == "2":  # Если выбрано извлечение, проверяем наличие элементов.
        if queue:  # Непустая очередь позволяет безопасно извлечь первый элемент.
            item = queue.popleft()  # Удаляем и получаем самый ранний из оставшихся элементов.
            print("Извлечён элемент:", item)  # Показываем извлечённое значение.
        else:  # Если очередь пустая, извлекать нечего.
            print("Очередь пуста. Извлечь элемент нельзя.")  # Сообщаем о пустой очереди вместо ошибки.

    elif choice == "3":  # Если выбран просмотр, проверяем наличие первого элемента.
        if queue:  # Обращаться к первому элементу можно только у непустой очереди.
            print("Первый элемент:", queue[0])  # Показываем первый элемент, оставляя его в очереди.
        else:  # У пустой очереди первого элемента нет.
            print("Очередь пуста. Первого элемента нет.")  # Объясняем, почему показать элемент невозможно.

    elif choice == "4":  # Если выбрана проверка пустоты, смотрим, есть ли элементы.
        if not queue:  # Пустая очередь при проверке даёт False, а not меняет его на True.
            print("Очередь пуста.")  # Сообщаем об отсутствии элементов.
        else:  # Иначе в очереди есть хотя бы один элемент.
            print("Очередь не пуста.")  # Сообщаем, что очередь содержит данные.

    elif choice == "5":  # Если выбран размер, считаем элементы.
        print("Размер очереди:", len(queue))  # len возвращает текущее количество элементов.

    elif choice == "6":  # Если выбран поиск, запрашиваем значение для проверки.
        item = input("Введите искомый элемент: ")  # Читаем искомое значение как текст, как и при добавлении.
        if item in queue:  # Проверяем, есть ли в очереди точно такое значение.
            print("Элемент есть в очереди.")  # Сообщаем об успешном поиске.
        else:  # Если значение не встретилось, поиск неуспешен.
            print("Элемента нет в очереди.")  # Сообщаем об отсутствии значения.

    elif choice == "7":  # Если выбрана очистка, удаляем все значения.
        queue.clear()  # Полностью очищаем очередь.
        print("Очередь очищена.")  # Подтверждаем выполнение команды.

    elif choice == "8":  # Если выбран полный просмотр, выводим элементы по порядку.
        if queue:  # Проверяем, есть ли элементы для вывода.
            print("Элементы от начала к концу очереди:")  # Объясняем порядок вывода.
            for item in queue:  # Перебираем элементы от самого раннего к самому позднему без удаления.
                print(item)  # Показываем очередной элемент на отдельной строке.
        else:  # Если очередь пустая, выводить нечего.
            print("Очередь пуста.")  # Сообщаем, что элементов нет.

    elif choice == "0":  # Если выбран выход, завершаем повторение меню.
        print("Работа с очередью завершена.")  # Показываем сообщение о завершении.
        break  # Выходим из цикла и заканчиваем программу.

    else:  # Сюда попадаем, если введён неизвестный пункт меню.
        print("Неизвестная команда. Выберите пункт меню от 0 до 8.")  # Объясняем допустимые команды и продолжаем работу.
