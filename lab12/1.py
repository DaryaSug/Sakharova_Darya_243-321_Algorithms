# Задание 1. Реализовать основные операции с очередью.
# Очередь работает по правилу FIFO: кто первым добавлен, тот первым извлекается.

from collections import deque  # Подключаем deque — готовую структуру для добавления и удаления с обоих концов.

queue = deque()  # Создаём пустую очередь; добавлять будем справа, а извлекать слева.

print("Работа с очередью:")  
print("1 — Добавить элемент") 
print("2 — Извлечь первый элемент")  
print("3 — Посмотреть первый элемент без удаления") 
print("4 — Проверить, пуста ли очередь") 
print("5 — Узнать размер очереди")  
print("6 — Проверить наличие элемента")  
print("7 — Очистить очередь") 
print("8 — Вывести все элементы") 
print("0 — Завершить работу") 

while True:  # Цикл
    choice = input("Выберите пункт меню: ").strip()  # Читаем номер команды как текст и убираем случайные пробелы по краям.

    if choice == "1":  # Если выбрано добавление, запрашиваем новое значение.
        item = input("Введите элемент очереди: ")  
        queue.append(item)  # Добавляем элемент в конец очереди.
        print("Добавлен элемент:", item)  

    elif choice == "2":  # Если выбрано извлечение, проверяем наличие элементов.
        if queue: 
            item = queue.popleft()  # Удаляем и получаем самый ранний из оставшихся элементов.
            print("Извлечён элемент:", item)  
        else:  # Если очередь пустая, извлекать нечего.
            print("Очередь пуста. Извлечь элемент нельзя.") 

    elif choice == "3":  # Если выбран просмотр, проверяем наличие первого элемента.
        if queue:  
            print("Первый элемент:", queue[0])  # Показываем первый элемент, оставляя его в очереди.
        else:  
            print("Очередь пуста. Первого элемента нет.")  

    elif choice == "4":  # Если выбрана проверка пустоты, смотрим, есть ли элементы.
        if not queue:  
            print("Очередь пуста.")  
        else:  
            print("Очередь не пуста.")  

    elif choice == "5":  # Если выбран размер, считаем элементы.
        print("Размер очереди:", len(queue))  # len возвращает текущее количество элементов.

    elif choice == "6":  # Если выбран поиск, запрашиваем значение для проверки.
        item = input("Введите искомый элемент: ")  
        if item in queue:  
            print("Элемент есть в очереди.")  
        else:  
            print("Элемента нет в очереди.")  

    elif choice == "7":  
        queue.clear()  # Полностью очищаем очередь.
        print("Очередь очищена.")  

    elif choice == "8":  # Если выбран полный просмотр, выводим элементы по порядку.
        if queue:  
            print("Элементы от начала к концу очереди:")  
            for item in queue:  # Перебираем элементы от самого раннего к самому позднему без удаления.
                print(item)  
        else:  
            print("Очередь пуста.") 

    elif choice == "0":  
        print("Работа с очередью завершена.")  
        break  

    else:  
        print("Неизвестная команда. Выберите пункт меню от 0 до 8.")  
