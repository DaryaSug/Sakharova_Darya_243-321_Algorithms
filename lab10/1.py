# Задание 1. Реализовать бинарный поиск через цикл while.
# Массив должен быть отсортирован от меньшего к большему; одинаковые числа допустимы.
# Индексы начинаются с 0. При повторениях возвращаем индекс одного из вхождений числа.

def binary_search(numbers, target):  # Функцию, которая возвращает индекс искомого числа
    left = 0  
    right = len(numbers) - 1  
    while left <= right:  # Продолжаем поиск, пока между границами остаются элементы.
        middle = (left + right) // 2  # Находим индекс середины; // оставляет целую часть от деления.
        middle_value = numbers[middle]  # Запоминаем значение среднего элемента.
        if middle_value == target:  
            return middle  
        elif middle_value > target:  # Если средний элемент больше искомого, искать нужно слева.
            right = middle - 1 
        else:  # Если средний элемент меньше искомого, искать нужно справа.
            left = middle + 1  
    return -1  # Если границы пересеклись, число не найдено.


n = int(input("Введите количество элементов N, не меньше 0: ")) 

if n < 0:  
    print("Количество элементов не может быть отрицательным.")  
else: 
    numbers = []  # Пустой список для чисел.
    print("Вводите элементы от меньшего к большему, одинаковые значения допустимы.") 
    for i in range(n):  # По очереди вводим все N элементов.
        value = float(input(f"Введите элемент {i + 1}: "))  
        numbers.append(value)  # Добавляем число в конец массива.
    target = float(input("Введите число для поиска: "))  
    index = binary_search(numbers, target)  # Вызываем функцию бинарного поиска.

    if index == -1:  
        print("Элемент не найден. Результат:", index)  
    else:  
        print("Индекс найденного элемента, считая с 0:", index) 
