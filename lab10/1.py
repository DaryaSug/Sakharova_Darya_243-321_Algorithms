# Задание 1. Реализовать бинарный поиск через цикл while.
# Массив должен быть отсортирован от меньшего к большему; одинаковые числа допустимы.
# Индексы начинаются с 0. При повторениях возвращаем индекс одного из вхождений числа.

def binary_search(numbers, target):  # Создаём функцию, которая возвращает индекс искомого числа либо -1.
    left = 0  # Сначала левая граница поиска — первый элемент массива.
    right = len(numbers) - 1  # Правая граница — последний элемент массива.
    while left <= right:  # Продолжаем поиск, пока между границами остаются элементы.
        middle = (left + right) // 2  # Находим индекс середины; // оставляет целую часть от деления.
        middle_value = numbers[middle]  # Запоминаем значение среднего элемента.
        if middle_value == target:  # Проверяем, совпало ли оно с искомым числом.
            return middle  # Если совпало, возвращаем индекс и завершаем функцию.
        elif middle_value > target:  # Если средний элемент больше искомого, искать нужно слева.
            right = middle - 1  # Исключаем середину и всё, что находится правее неё.
        else:  # Если средний элемент меньше искомого, искать нужно справа.
            left = middle + 1  # Исключаем середину и всё, что находится левее неё.
    return -1  # Если границы пересеклись, число не найдено.


n = int(input("Введите количество элементов N, не меньше 0: "))  # Вводим размер массива; ноль означает пустой массив.

if n < 0:  # Проверяем, не ввели ли отрицательное количество элементов.
    print("Количество элементов не может быть отрицательным.")  # Сообщаем о неверном размере.
else:  # Для допустимого размера вводим отсортированный массив и выполняем поиск.
    numbers = []  # Создаём пустой список для чисел.
    print("Вводите элементы от меньшего к большему, одинаковые значения допустимы.")  # Напоминаем обязательное условие бинарного поиска.
    for i in range(n):  # По очереди вводим все N элементов.
        value = float(input(f"Введите элемент {i + 1}: "))  # Вводим очередное число, можно отрицательное или дробное.
        numbers.append(value)  # Добавляем число в конец массива.
    target = float(input("Введите число для поиска: "))  # Вводим значение, которое нужно найти.
    index = binary_search(numbers, target)  # Вызываем функцию бинарного поиска.

    if index == -1:  # Проверяем, сообщила ли функция об отсутствии числа.
        print("Элемент не найден. Результат:", index)  # Выводим -1, как требуется в задании.
    else:  # Если функция вернула другой индекс, число найдено.
        print("Индекс найденного элемента, считая с 0:", index)  # Показываем индекс; у первого элемента он равен 0.
