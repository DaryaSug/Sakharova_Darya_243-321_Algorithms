# Задание 4. Определить четверть точки, не лежащей на координатных осях.

x = float(input("Введите x: "))  # Вводим горизонтальную координату точки.
y = float(input("Введите y: "))  # Вводим вертикальную координату точки.

if x > 0 and y > 0:  # В первой четверти обе координаты положительные.
    print("Номер координатной четверти: 1")  # Выводим первую четверть.
elif x < 0 and y > 0:  # Во второй четверти x отрицательный, а y положительный.
    print("Номер координатной четверти: 2")  # Выводим вторую четверть.
elif x < 0 and y < 0:  # В третьей четверти обе координаты отрицательные.
    print("Номер координатной четверти: 3")  # Выводим третью четверть.
elif x > 0 and y < 0:  # В четвёртой четверти x положительный, а y отрицательный.
    print("Номер координатной четверти: 4")  # Выводим четвёртую четверть.
else:  # Если хотя бы одна координата равна нулю, точка находится на оси.
    print("Точка лежит на координатной оси и не относится ни к одной четверти.")  # Объясняем результат.
