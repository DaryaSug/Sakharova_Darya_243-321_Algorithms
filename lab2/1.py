# Задание 1. Если целые A и B различаются, заменить оба числа большим из них.
# Если числа равны, заменить оба нулями. Вывести новые A и B.

a = int(input("Введите целое число A: "))  # Вводим первое целое число.
b = int(input("Введите целое число B: "))  # Вводим второе целое число.

if a > b:  # Если A больше B, нужно заменить B значением A.
    b = a  # Теперь оба числа равны прежнему значению A.
elif b > a:  # Иначе проверяем, больше ли B, чем A.
    a = b  # Теперь оба числа равны прежнему значению B.
else:  # Если ни одно число не больше другого, они равны.
    a = 0  # Присваиваем A ноль по условию задания.
    b = 0  # Присваиваем B ноль по условию задания.

print("Новое значение A:", a)  # Выводим изменённое A.
print("Новое значение B:", b)  # Выводим изменённое B.
