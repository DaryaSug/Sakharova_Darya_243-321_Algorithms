# Задание 7. По номеру дня и месяца вывести дату словами, например «пятое января».
# Год не задан, поэтому 29 февраля допускается как возможная дата.

day = int(input("Введите номер дня от 1 до 31: "))  # Вводим номер дня месяца.
month = int(input("Введите номер месяца от 1 до 12: "))  # Вводим номер месяца.

months = ("января", "февраля", "марта", "апреля", "мая", "июня", "июля", "августа", "сентября", "октября", "ноября", "декабря")  # Названия месяцев в нужной форме.
month_lengths = (31, 29, 31, 30, 31, 30, 31, 31, 30, 31, 30, 31)  # Максимальное количество дней в каждом месяце.
days = ("первое", "второе", "третье", "четвертое", "пятое", "шестое", "седьмое", "восьмое", "девятое", "десятое", "одиннадцатое", "двенадцатое", "тринадцатое", "четырнадцатое", "пятнадцатое", "шестнадцатое", "семнадцатое", "восемнадцатое", "девятнадцатое")  # Готовые названия дней с 1 по 19.

if month < 1 or month > 12:  # Проверяем номер месяца перед обращением к набору названий.
    print("Нужно ввести номер месяца от 1 до 12.")  # Сообщаем о неверном месяце.
elif day < 1 or day > month_lengths[month - 1]:  # Индексы начинаются с 0, поэтому из номера месяца вычитаем 1.
    print("Такого дня в указанном месяце нет.")  # Сообщаем о невозможном дне месяца.
else:  # Для допустимой даты подбираем название дня.
    if day <= 19:  # Для первых девятнадцати дней название уже готово.
        day_text = days[day - 1]  # Берём название по номеру дня минус 1.
    elif day == 20:  # У двадцатого дня отдельное название.
        day_text = "двадцатое"  # Сохраняем это название.
    elif day < 30:  # Здесь остаются дни с 21 по 29.
        day_text = "двадцать " + days[day % 10 - 1]  # Добавляем к слову «двадцать» название последней цифры.
    elif day == 30:  # Для тридцатого дня тоже нужно отдельное слово.
        day_text = "тридцатое"  # Сохраняем название дня.
    else:  # Единственный оставшийся допустимый день — 31.
        day_text = "тридцать первое"  # Сохраняем название последнего дня месяца.

    print(day_text, months[month - 1])  # Выводим день и название месяца через пробел.
