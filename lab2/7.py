day = int(input("Введите номер дня от 1 до 31: "))
month = int(input("Введите номер месяца от 1 до 12: "))

months = ("января", "февраля", "марта", "апреля", "мая", "июня", "июля", "августа", "сентября", "октября", "ноября", "декабря")
month_lengths = (31, 29, 31, 30, 31, 30, 31, 31, 30, 31, 30, 31)
days = ("первое", "второе", "третье", "четвертое", "пятое", "шестое", "седьмое", "восьмое", "девятое", "десятое", "одиннадцатое", "двенадцатое", "тринадцатое", "четырнадцатое", "пятнадцатое", "шестнадцатое", "семнадцатое", "восемнадцатое", "девятнадцатое")

if month < 1 or month > 12:
    print("Нужно ввести номер месяца от 1 до 12.")
elif day < 1 or day > month_lengths[month - 1]:
    print("Такого дня в указанном месяце нет.")
else:
    if day <= 19:
        day_text = days[day - 1]
    elif day == 20:
        day_text = "двадцатое"
    elif day < 30:
        day_text = "двадцать " + days[day % 10 - 1]
    elif day == 30:
        day_text = "тридцатое"
    else:
        day_text = "тридцать первое"

    print(day_text, months[month - 1])
