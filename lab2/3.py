# Задание 3. Из точек B и C выбрать ближайшую к A и найти расстояние до неё.

from math import sqrt  # Подключаем функцию квадратного корня.

ax = float(input("Введите x точки A: "))  # Вводим координату x точки A.
ay = float(input("Введите y точки A: "))  # Вводим координату y точки A.
bx = float(input("Введите x точки B: "))  # Вводим координату x точки B.
by = float(input("Введите y точки B: "))  # Вводим координату y точки B.
cx = float(input("Введите x точки C: "))  # Вводим координату x точки C.
cy = float(input("Введите y точки C: "))  # Вводим координату y точки C.

ab = sqrt((bx - ax) ** 2 + (by - ay) ** 2)  # Находим расстояние от A до B по формуле расстояния.
ac = sqrt((cx - ax) ** 2 + (cy - ay) ** 2)  # Так же находим расстояние от A до C.

if ab < ac:  # Если расстояние до B меньше, выбираем B.
    print("Ближе точка B с координатами:", bx, by)  # Показываем название и координаты точки.
    print("Расстояние от A:", ab)  # Показываем расстояние до B.
elif ac < ab:  # Иначе проверяем, ближе ли точка C.
    print("Ближе точка C с координатами:", cx, cy)  # Показываем название и координаты точки.
    print("Расстояние от A:", ac)  # Показываем расстояние до C.
else:  # Если расстояния равны, обе точки одинаково близки к A.
    print("Точки B и C находятся на одинаковом расстоянии от A.")  # Сообщаем о равенстве.
    print("Координаты B:", bx, by)  # Показываем координаты B.
    print("Координаты C:", cx, cy)  # Показываем координаты C.
    print("Расстояние от A:", ab)  # Выводим общее расстояние.
