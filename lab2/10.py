# Задание 10. Назвать год по 60-летнему циклу; 1984 — год зеленой крысы.
# По условию документа каждый цвет относится к целому 12-летнему подциклу.

year = int(input("Введите год: "))  # Вводим номер года.

cycle_year = (year - 1984) % 60  # Находим позицию года в цикле: от 0 до 59, начиная с 1984 года.
color_number = cycle_year // 12  # Делим цикл на пять цветных отрезков по 12 лет.
animal_number = cycle_year % 12  # Находим номер животного внутри 12-летнего подцикла.

animals = ("крысы", "коровы", "тигра", "зайца", "дракона", "змеи", "лошади", "овцы", "обезьяны", "курицы", "собаки", "свиньи")  # Названия животных для фразы «год кого».
masculine_colors = ("зеленого", "красного", "желтого", "белого", "черного")  # Формы цвета для тигра, зайца и дракона.
feminine_colors = ("зеленой", "красной", "желтой", "белой", "черной")  # Формы цвета для остальных животных.

if animal_number == 2 or animal_number == 3 or animal_number == 4:  # Проверяем, выбраны ли тигр, заяц или дракон.
    color = masculine_colors[color_number]  # Берём форму цвета мужского рода, например «зеленого».
else:  # Названия остальных животных в задании женского рода.
    color = feminine_colors[color_number]  # Берём форму цвета женского рода, например «зеленой».

print("год", color, animals[animal_number])  # Собираем и выводим название года через пробелы.
