# Задание 9. Записать словами целое число от 100 до 999.

number = int(input("Введите целое число от 100 до 999: "))  # Вводим трёхзначное число.

hundreds = ("", "сто", "двести", "триста", "четыреста", "пятьсот", "шестьсот", "семьсот", "восемьсот", "девятьсот")  # Названия сотен по их первой цифре.
tens = ("", "", "двадцать", "тридцать", "сорок", "пятьдесят", "шестьдесят", "семьдесят", "восемьдесят", "девяносто")  # Названия десятков от 20 до 90.
teens = ("десять", "одиннадцать", "двенадцать", "тринадцать", "четырнадцать", "пятнадцать", "шестнадцать", "семнадцать", "восемнадцать", "девятнадцать")  # Отдельные названия чисел 10–19.
units = ("", "один", "два", "три", "четыре", "пять", "шесть", "семь", "восемь", "девять")  # Названия единиц; ноль отдельно не произносим.

if number < 100 or number > 999:  # Проверяем, что число трёхзначное и положительное.
    print("Нужно ввести число от 100 до 999.")  # Сообщаем о выходе за диапазон.
else:  # Переводим допустимое число в слова.
    result = hundreds[number // 100]  # Деление // отбрасывает дробную часть и даёт цифру сотен.
    remainder = number % 100  # Остаток от деления на 100 даёт последние две цифры.

    if 10 <= remainder <= 19:  # Числа 10–19 записываются одним отдельным словом.
        result = result + " " + teens[remainder - 10]  # Добавляем подходящее слово после сотен.
    else:  # В остальных случаях десятки и единицы записываем отдельно.
        if remainder >= 20:  # Если есть десятки от 20 до 90, добавляем их название.
            result = result + " " + tens[remainder // 10]  # Получаем цифру десятков и выбираем слово.
        if remainder % 10 != 0:  # Проверяем, есть ли ненулевые единицы.
            result = result + " " + units[remainder % 10]  # Добавляем название последней цифры.

    print(result)  # Показываем число, записанное словами.
