# Задание 6. Описать чётность и количество цифр целого числа от 1 до 999.

number = int(input("Введите целое число от 1 до 999: "))  # Вводим число для описания.

if number < 1 or number > 999:  # Проверяем, не вышло ли число за границы задания.
    print("Нужно ввести число от 1 до 999.")  # Сообщаем, какой диапазон допустим.
else:  # Если число подходит, составляем его описание.
    if number % 2 == 0:  # Проверяем остаток от деления числа на 2.
        parity = "четное"  # Если остаток нулевой, число чётное.
    else:  # Иначе число нечётное.
        parity = "нечетное"  # Сохраняем нужное слово.

    if number < 10:  # У чисел от 1 до 9 одна цифра.
        digits = "однозначное"  # Запоминаем описание количества цифр.
    elif number < 100:  # У оставшихся чисел меньше 100 две цифры.
        digits = "двузначное"  # Запоминаем описание для двух цифр.
    else:  # Все оставшиеся допустимые числа имеют три цифры.
        digits = "трехзначное"  # Запоминаем описание для трёх цифр.

    print(parity, digits, "число")  # Выводим готовое описание.
