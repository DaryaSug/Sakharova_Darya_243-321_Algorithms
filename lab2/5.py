# Задание 5. Описать целое число: его знак и чётность, отдельно выделить ноль.

number = int(input("Введите целое число: "))  # Вводим число без дробной части.

if number == 0:  # Сначала проверяем особый случай — ноль.
    print("нулевое число")  # Для нуля выводим описание из условия.
else:  # Для остальных чисел определяем знак и чётность.
    if number > 0:  # Проверяем, больше ли число нуля.
        sign = "положительное"  # Запоминаем слово для положительного числа.
    else:  # Если ненулевое число не положительное, оно отрицательное.
        sign = "отрицательное"  # Запоминаем слово для отрицательного числа.

    if number % 2 == 0:  # Остаток от деления на 2 равен нулю у чётных чисел.
        parity = "четное"  # Запоминаем описание чётности.
    else:  # Ненулевой остаток означает, что число нечётное.
        parity = "нечетное"  # Запоминаем описание нечётности.

    print(sign, parity, "число")  # Соединяем слова пробелами и выводим описание.
