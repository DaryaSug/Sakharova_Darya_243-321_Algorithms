# Задание 2. Даны три числа. Найти сумму двух наибольших.

a = float(input("Введите первое число: "))  # Вводим первое число, можно дробное.
b = float(input("Введите второе число: "))  # Вводим второе число.
c = float(input("Введите третье число: "))  # Вводим третье число.

if a <= b and a <= c:  # Проверяем, что A не больше двух остальных чисел.
    result = b + c  # Исключаем наименьшее A и складываем B и C.
elif b <= a and b <= c:  # Иначе проверяем, является ли B наименьшим.
    result = a + c  # Исключаем B и складываем A и C.
else:  # В остальных случаях наименьшим является C.
    result = a + b  # Складываем два остальных числа.

print("Сумма двух наибольших чисел:", result)  # Показываем найденную сумму.
