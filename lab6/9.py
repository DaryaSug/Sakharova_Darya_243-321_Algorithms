# Задание 9. Упорядочить строки по возрастанию их первых элементов.
# При одинаковых первых элементах сохраняем исходный порядок соответствующих строк.

m = int(input("Введите положительное число строк M: "))  # Вводим количество строк.
n = int(input("Введите положительное число столбцов N: "))  # Вводим количество столбцов.
matrix = []  # Создаём пустую матрицу.

for i in range(m):  # По очереди заполняем строки матрицы.
    row = []  # Создаём новую строку.
    for j in range(n):  # Вводим все числа текущей строки.
        value = float(input(f"Введите A{i + 1},{j + 1}: "))  # Читаем очередной элемент.
        row.append(value)  # Сохраняем число в строке.
    matrix.append(row)  # Добавляем строку в матрицу.

for i in range(m - 1):  # Делаем проходы сортировки пузырьком.
    for j in range(m - 1 - i):  # Сравниваем соседние строки в ещё не отсортированной части.
        if matrix[j][0] > matrix[j + 1][0]:  # Сравниваем только первые элементы этих строк.
            matrix[j], matrix[j + 1] = matrix[j + 1], matrix[j]  # Если порядок нарушен, меняем местами строки целиком.

print("Матрица после упорядочивания строк:")  # Выводим подпись к результату.
for row in matrix:  # Перебираем строки в новом порядке.
    print(*row)  # Выводим все элементы каждой строки.
