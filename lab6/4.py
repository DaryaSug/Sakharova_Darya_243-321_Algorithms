# Задание 4. В каждом столбце посчитать элементы, которые строго больше среднего этого столбца.

m = int(input("Введите положительное число строк M: "))  # Вводим количество строк.
n = int(input("Введите положительное число столбцов N: "))  # Вводим количество столбцов.
matrix = []  # Создаём список для строк матрицы.

for i in range(m):  # По очереди вводим строки.
    row = []  # Создаём пустую строку.
    for j in range(n):  # Заполняем все столбцы текущей строки.
        value = float(input(f"Введите A{i + 1},{j + 1}: "))  # Вводим очередной элемент матрицы.
        row.append(value)  # Добавляем элемент в текущую строку.
    matrix.append(row)  # Добавляем строку в матрицу.

for j in range(n):  # Обрабатываем каждый столбец отдельно.
    total = 0  # Начинаем сумму элементов столбца с нуля.
    for i in range(m):  # Проходим по всем строкам этого столбца.
        total = total + matrix[i][j]  # Прибавляем очередной элемент к сумме.
    average = total / m  # Делим сумму на число строк и получаем среднее столбца.
    count = 0  # Пока не найдено ни одного элемента больше среднего.
    for i in range(m):  # Ещё раз просматриваем элементы этого столбца.
        if matrix[i][j] > average:  # Сравниваем элемент со средним именно его столбца.
            count = count + 1  # Увеличиваем счётчик подходящих элементов.
    print(f"Столбец {j + 1}, количество элементов больше среднего:", count)  # Выводим номер столбца и ответ для него.
