# Задание 3. Найти столбец с наименьшим произведением элементов и вывести его номер и произведение.
# Если наименьшее произведение одинаково у нескольких столбцов, выбираем первый.

m = int(input("Введите положительное число строк M: "))  # Вводим количество строк.
n = int(input("Введите положительное число столбцов N: "))  # Вводим количество столбцов.
matrix = []  # Создаём пустую матрицу.

for i in range(m):  # Заполняем матрицу по строкам.
    row = []  # Создаём новую строку.
    for j in range(n):  # Вводим все числа очередной строки.
        value = float(input(f"Введите A{i + 1},{j + 1}: "))  # Вводим элемент с указанными номерами строки и столбца.
        row.append(value)  # Добавляем число в строку.
    matrix.append(row)  # Сохраняем готовую строку в матрице.

minimum_product = None  # Пока минимальное произведение неизвестно.
column_number = 0  # Здесь сохраним номер подходящего столбца.

for j in range(n):  # По очереди рассматриваем каждый столбец.
    product = 1  # Для нового столбца начинаем произведение с единицы.
    for i in range(m):  # Проходим все строки выбранного столбца.
        product = product * matrix[i][j]  # Умножаем результат на очередной элемент столбца.
    if minimum_product is None or product < minimum_product:  # Первый результат запоминаем сразу, остальные сравниваем с ним.
        minimum_product = product  # Сохраняем новое наименьшее произведение.
        column_number = j + 1  # Превращаем индекс столбца в номер, начиная с 1.

print("Номер столбца:", column_number)  # Выводим номер выбранного столбца.
print("Наименьшее произведение:", minimum_product)  # Выводим произведение его элементов.
