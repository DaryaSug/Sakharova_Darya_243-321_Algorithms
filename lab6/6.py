# Задание 6. В каждой строке поменять местами минимальный и максимальный элементы.
# При повторениях выбираем первое вхождение минимума и первое вхождение максимума в строке.

m = int(input("Введите положительное число строк M: "))  # Вводим число строк.
n = int(input("Введите положительное число столбцов N: "))  # Вводим число столбцов.
matrix = []  # Создаём пустую матрицу.

for i in range(m):  # По очереди вводим строки матрицы.
    row = []  # Создаём список для новой строки.
    for j in range(n):  # Вводим N чисел строки.
        value = float(input(f"Введите A{i + 1},{j + 1}: "))  # Читаем очередной элемент.
        row.append(value)  # Сохраняем элемент в строке.
    matrix.append(row)  # Сохраняем готовую строку в матрице.

for row in matrix:  # Преобразуем каждую строку отдельно.
    min_index = 0  # Пока считаем первый элемент минимальным.
    max_index = 0  # Пока считаем первый элемент максимальным.
    for j in range(1, n):  # Сравниваем с ними остальные элементы строки.
        if row[j] < row[min_index]:  # Проверяем, найдено ли меньшее значение.
            min_index = j  # Запоминаем индекс нового минимума.
        if row[j] > row[max_index]:  # Проверяем, найдено ли большее значение.
            max_index = j  # Запоминаем индекс нового максимума.
    row[min_index], row[max_index] = row[max_index], row[min_index]  # Одновременно меняем два найденных элемента местами.

print("Преобразованная матрица:")  # Выводим подпись перед результатом.
for row in matrix:  # Перебираем строки изменённой матрицы.
    print(*row)  # Выводим элементы строки через пробелы.
