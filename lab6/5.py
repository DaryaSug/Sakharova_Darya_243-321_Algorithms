# Задание 5. Найти номер первого столбца, содержащего только нечётные целые числа.
# Если такого столбца нет, вывести 0.

m = int(input("Введите положительное число строк M: ")) 
n = int(input("Введите положительное число столбцов N: "))  
matrix = []  

for i in range(m):  
    row = []  
    for j in range(n):  
        value = int(input(f"Введите целое A{i + 1},{j + 1}: "))  
        row.append(value)  
    matrix.append(row) 

column_number = 0  

for j in range(n):  # Проверяем столбцы слева направо, чтобы найти первый подходящий.
    all_odd = True  # Пока считаем, что все числа текущего столбца нечётные.
    for i in range(m):  # Проверяем каждое число в столбце.
        if matrix[i][j] % 2 == 0:  # Если остаток от деления на 2 нулевой, число чётное.
            all_odd = False  # Запоминаем, что этот столбец не подходит.
            break  
    if all_odd:  # Если чётных чисел не нашли, весь столбец подходит.
        column_number = j + 1  # Сохраняем номер столбца, начиная с 1.
        break  

print("Номер первого столбца только с нечётными числами:", column_number)  
