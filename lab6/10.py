# Задание 10. Найти суммы диагоналей квадратной матрицы, идущих параллельно главной.
# Выводим от одноэлементной диагонали в правом верхнем углу к левому нижнему углу, включая главную.

m = int(input("Введите положительный порядок квадратной матрицы M: "))  # Вводим число строк и столбцов.
matrix = []  # Создаём список для строк матрицы.

for i in range(m):  # По очереди заполняем строки.
    row = []  # Создаём новую строку матрицы.
    for j in range(m):  # Вводим M чисел этой строки.
        value = float(input(f"Введите A{i + 1},{j + 1}: "))  # Вводим элемент с заданными номерами строки и столбца.
        row.append(value)  # Добавляем число в строку.
    matrix.append(row)  # Добавляем строку в матрицу.

for offset in range(m - 1, -m, -1):  # Разность индексов столбца и строки постоянна на каждой такой диагонали.
    if offset >= 0:  # Диагонали над главной и сама главная начинаются в первой строке.
        i = 0  # Начинаем с верхней строки.
        j = offset  # Смещение задаёт начальный столбец.
    else:  # Диагонали под главной начинаются в первом столбце.
        i = -offset  # Отрицательное смещение задаёт начальную строку.
        j = 0  # Начинаем с первого столбца.
    start_row = i + 1  # Запоминаем номер начальной строки для подписи к результату.
    start_column = j + 1  # Запоминаем номер начального столбца.
    total = 0  # Начинаем сумму текущей диагонали с нуля.
    while i < m and j < m:  # Двигаемся по диагонали, пока не вышли за границы матрицы.
        total = total + matrix[i][j]  # Добавляем очередной элемент диагонали.
        i = i + 1  # Переходим на строку ниже.
        j = j + 1  # Одновременно переходим на столбец правее.
    print(f"Сумма диагонали с началом в A{start_row},{start_column}:", total)  # Выводим сумму и указываем начало диагонали.
