# Задание 2. Найти сумму и произведение элементов K-й строки матрицы M на N.
# Номера строк начинаются с 1; по условию 1 <= K <= M.

m = int(input("Введите положительное число строк M: "))  
n = int(input("Введите положительное число столбцов N: "))  
matrix = []  

for i in range(m):  
    row = []  
    for j in range(n):  
        value = float(input(f"Введите A{i + 1},{j + 1}: "))  
        row.append(value)  # Добавляем число в строку.
    matrix.append(row)  # Добавляем заполненную строку в матрицу.

k = int(input("Введите номер строки K: "))  
if k < 1 or k > m:  
    print("Номер строки должен быть от 1 до M.")  
else:  
    total = 0  
    product = 1  
    for value in matrix[k - 1]:  # получаем индекс 
        total = total + value  # Прибавляем очередной элемент к сумме.
        product = product * value  # Умножаем накопленное произведение на этот элемент.
    print("Сумма элементов строки:", total)  
    print("Произведение элементов строки:", product) 
