# Задание 2. Найти сумму и произведение элементов K-й строки матрицы M на N.
# Номера строк начинаются с 1; по условию 1 <= K <= M.

m = int(input("Введите положительное число строк M: "))  # Вводим количество строк матрицы.
n = int(input("Введите положительное число столбцов N: "))  # Вводим количество столбцов.
matrix = []  # Создаём пустую матрицу.

for i in range(m):  # По очереди заполняем строки матрицы.
    row = []  # Подготавливаем список для очередной строки.
    for j in range(n):  # Вводим все элементы этой строки.
        value = float(input(f"Введите A{i + 1},{j + 1}: "))  # Читаем число в строке i+1 и столбце j+1.
        row.append(value)  # Добавляем число в строку.
    matrix.append(row)  # Добавляем заполненную строку в матрицу.

k = int(input("Введите номер строки K: "))  # Вводим номер строки для вычислений.

if k < 1 or k > m:  # Проверяем, существует ли строка с таким номером.
    print("Номер строки должен быть от 1 до M.")  # Сообщаем о неверном номере.
else:  # Для существующей строки вычисляем сумму и произведение.
    total = 0  # Начальная сумма равна нулю.
    product = 1  # Начальное произведение равно единице.
    for value in matrix[k - 1]:  # Вычитаем 1 из номера строки, чтобы получить индекс Python.
        total = total + value  # Прибавляем очередной элемент к сумме.
        product = product * value  # Умножаем накопленное произведение на этот элемент.
    print("Сумма элементов строки:", total)  # Выводим найденную сумму.
    print("Произведение элементов строки:", product)  # Выводим найденное произведение.
