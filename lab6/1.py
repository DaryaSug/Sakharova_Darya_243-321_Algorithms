# Задание 1. Вывести квадратную матрицу нечётного порядка по спирали против часовой стрелки.


m = int(input("Введите положительный нечётный порядок матрицы M: "))  

if m <= 0 or m % 2 == 0:  
    print("Порядок матрицы должен быть положительным нечётным числом.") 
else: 
    matrix = []  
    for i in range(m):  # По очереди заполняем все строки.
        row = []  
        for j in range(m):  
            value = float(input(f"Введите A{i + 1},{j + 1}: "))  # Вводим число на пересечении строки i+1 и столбца j+1.
            row.append(value)  # Добавляем число в текущую строку.
        matrix.append(row)  # Добавляем готовую строку в матрицу.

    top = 0  
    bottom = m - 1  
    left = 0
    right = m - 1 
    result = []  

    while top <= bottom and left <= right:  
        for i in range(top, bottom + 1):  # Идём вниз по левому столбцу оставшейся части.
            result.append(matrix[i][left])  # Добавляем очередной элемент спирали.
        left = left + 1  # Исключаем уже пройденный левый столбец.
        for j in range(left, right + 1):  # Идём вправо по нижней строке.
            result.append(matrix[bottom][j])  # Добавляем элемент нижней стороны спирали.
        bottom = bottom - 1  # Исключаем пройденную нижнюю строку.
        if left <= right:  # Проверяем, остался ли столбец для движения вверх.
            for i in range(bottom, top - 1, -1):  # Идём вверх по правому столбцу.
                result.append(matrix[i][right])  # Добавляем элемент правой стороны спирали.
            right = right - 1  # Исключаем пройденный правый столбец.
        if top <= bottom:  # Проверяем, осталась ли строка для движения влево.
            for j in range(right, left - 1, -1):  # Идём влево по верхней строке.
                result.append(matrix[top][j])  # Добавляем элемент верхней стороны спирали.
            top = top + 1  # Исключаем пройденную верхнюю строку.

    print("Элементы по спирали:", *result)  # Звёздочка выводит элементы списка через пробелы.
