# Задание 8. В матрице с чётными M и N поменять местами левую верхнюю и правую нижнюю четверти.

m = int(input("Введите положительное чётное число строк M: "))  # Вводим количество строк.
n = int(input("Введите положительное чётное число столбцов N: "))  # Вводим количество столбцов.

if m <= 0 or n <= 0 or m % 2 != 0 or n % 2 != 0:  # Проверяем, что оба размера положительные и чётные.
    print("Оба размера матрицы должны быть положительными чётными числами.")  # Сообщаем о неподходящих размерах.
else:  # Для допустимых размеров вводим и преобразуем матрицу.
    matrix = []  # Создаём пустую матрицу.
    for i in range(m):  # Вводим строки сверху вниз.
        row = []  # Создаём новую строку.
        for j in range(n):  # Вводим все элементы этой строки.
            value = float(input(f"Введите A{i + 1},{j + 1}: "))  # Читаем очередное число.
            row.append(value)  # Добавляем его в строку.
        matrix.append(row)  # Добавляем готовую строку в матрицу.

    half_rows = m // 2  # Половина строк — высота одной четверти.
    half_columns = n // 2  # Половина столбцов — ширина одной четверти.

    for i in range(half_rows):  # Перебираем строки левой верхней четверти.
        for j in range(half_columns):  # Перебираем её столбцы.
            matrix[i][j], matrix[i + half_rows][j + half_columns] = matrix[i + half_rows][j + half_columns], matrix[i][j]  # Меняем элемент с соответствующим элементом правой нижней четверти.

    print("Преобразованная матрица:")  # Выводим подпись перед результатом.
    for row in matrix:  # Перебираем строки изменённой матрицы.
        print(*row)  # Выводим каждую строку через пробелы.
