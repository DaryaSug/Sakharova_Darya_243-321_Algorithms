# Задание 1. По цене 1 кг конфет вывести стоимость 0.1, 0.2, ..., 1 кг.

price = float(input("Введите цену 1 кг конфет: "))  # Вводим стоимость одного килограмма.

for i in range(1, 11):  # Перебираем целые числа от 1 до 10 включительно.
    weight = i / 10  # Получаем массу конфет: 0.1, 0.2 и так далее до 1 кг.
    cost = price * weight  # Умножаем цену килограмма на нужную массу.
    print(f"{weight:.1f} кг — {cost:.2f} руб.")  # Выводим массу с одной цифрой после точки, а стоимость — с двумя.
