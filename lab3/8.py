# Задание 8. Для целого N > 1 найти наименьшее K, при котором 1 + 2 + ... + K >= N.
# Вывести K и полученную сумму.

n = int(input("Введите целое число N больше 1: "))  # Вводим число, которого должна достичь сумма.
k = 0  # Пока не добавили ни одного натурального числа.
total = 0  # Начальная сумма равна нулю.

while total < n:  # Прибавляем числа, пока сумма меньше N.
    k = k + 1  # Переходим к следующему натуральному числу.
    total = total + k  # Прибавляем его к сумме.

print("Наименьшее K:", k)  # Показываем последнее добавленное число.
print("Сумма:", total)  # Показываем первую сумму, которая достигла N или превысила его.
