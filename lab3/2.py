# Задание 2. Найти произведение 1.1 * 1.2 * 1.3 * ... из N сомножителей, N > 0.

n = int(input("Введите целое число N больше 0: "))  # Вводим количество множителей.
product = 1  # Начинаем с 1, потому что умножение на 1 не меняет результат.

for i in range(1, n + 1):  # Повторяем вычисление N раз; правая граница range не включается.
    factor = 1 + i / 10  # Получаем очередной множитель: 1.1, 1.2, 1.3 и так далее.
    product = product * factor  # Умножаем накопленный результат на новый множитель.

print("Произведение:", product)  # Выводим произведение всех N множителей.
