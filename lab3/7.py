# Задание 7. На отрезке A разместить максимум отрезков B, A > B > 0.
# Найти незанятую длину, не используя умножение и деление.

from decimal import Decimal  # Подключаем десятичные числа, чтобы точно вычитать, например, 0.1 из 0.3.

a = Decimal(input("Введите положительную длину A: "))  # Вводим длину большого отрезка через точку, если она дробная.
b = Decimal(input("Введите положительную длину B меньше A: "))  # Вводим длину одного маленького отрезка.
remainder = a  # В начале весь большой отрезок свободен.

while remainder >= b:  # Пока в свободную часть помещается ещё один отрезок B, продолжаем цикл.
    remainder = remainder - b  # Размещаем один отрезок B и уменьшаем свободную длину.

print("Длина незанятой части:", remainder)  # Выводим остаток, в который ещё один отрезок B уже не помещается.
