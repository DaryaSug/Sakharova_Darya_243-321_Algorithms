# Задание 10. Найти НОД двух положительных целых чисел алгоритмом Евклида.
# НОД — наибольшее целое число, на которое оба исходных числа делятся без остатка.

a = int(input("Введите положительное целое число A: "))  # Вводим первое число.
b = int(input("Введите положительное целое число B: "))  # Вводим второе число.

while b != 0:  # Повторяем действия, пока второе число не стало нулём.
    remainder = a % b  # Находим остаток от деления первого числа на второе.
    a = b  # Переносим второе число на место первого.
    b = remainder  # Ставим полученный остаток на место второго числа.

print("Наибольший общий делитель:", a)  # Когда остаток стал нулём, первое число содержит НОД.
