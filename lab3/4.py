# Задание 4. Используя один цикл, найти сумму 1 + A + A^2 + ... + A^N, N > 0.

a = float(input("Введите число A: "))  # Вводим основание степеней, можно дробное.
n = int(input("Введите целое число N больше 0: "))  # Вводим наибольшую степень.
power = 1  # Начинаем со степени A^0, которая равна 1.
total = 1  # Первое слагаемое суммы уже равно 1.

for i in range(1, n + 1):  # В одном цикле перебираем степени от 1 до N.
    power = power * a  # Умножаем предыдущую степень на A и получаем следующую.
    total = total + power  # Прибавляем полученную степень к сумме.

print("Сумма степеней:", total)  # Выводим сумму вместе с первым слагаемым 1.
