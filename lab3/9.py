# Задание 9. Начальный вклад 1000 руб. ежемесячно увеличивается на P процентов.
# При 0 < P < 25 найти число месяцев, через которое вклад превысит 1100 руб., и итоговую сумму.

p = float(input("Введите месячный процент P, больше 0 и меньше 25: "))  # Вводим процент ежемесячного увеличения вклада.
s = 1000.0  # Начальная сумма вклада равна 1000 рублям.
k = 0  # В начале ещё не прошло ни одного месяца.

while s <= 1100:  # Продолжаем, пока вклад не стал строго больше 1100 рублей.
    s = s + s * p / 100  # Прибавляем проценты от текущей суммы, а не от начальной.
    k = k + 1  # Учитываем ещё один прошедший месяц.

print("Количество месяцев:", k)  # Выводим, через сколько месяцев достигнут нужный результат.
print("Итоговый размер вклада:", s, "руб.")  # Выводим итоговую сумму без промежуточного округления.
