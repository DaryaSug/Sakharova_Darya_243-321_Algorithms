# Задание 5. Одним циклом найти 1 - A + A^2 - A^3 + ... до степени N, N > 0.
# Условный оператор не используется: знаки меняются при умножении на -A.

a = float(input("Введите число A: "))  # Вводим число, степени которого складываем с разными знаками.
n = int(input("Введите целое число N больше 0: "))  # Вводим наибольшую степень.
term = 1  # Первое слагаемое равно 1.
total = 1  # Сразу включаем первое слагаемое в сумму.

for i in range(1, n + 1):  # Одним циклом получаем остальные N слагаемых.
    term = term * (-a)  # Получаем по очереди -A, A^2, -A^3 и следующие слагаемые.
    total = total + term  # Добавляем слагаемое вместе с его знаком.

print("Значение выражения:", total)  # Выводим итоговую сумму.
