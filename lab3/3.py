# Задание 3. Найти квадрат N как сумму первых N нечётных чисел, N > 0.
# После каждого прибавления выводить текущую сумму.

n = int(input("Введите целое число N больше 0: "))  # Вводим число, квадрат которого нужно найти.
total = 0  # Пока ни одного числа не прибавили, сумма равна нулю.

for i in range(1, n + 1):  # Перебираем номера слагаемых от 1 до N.
    odd = 2 * i - 1  # Получаем очередное нечётное число: 1, 3, 5 и так далее.
    total = total + odd  # Добавляем это число к накопленной сумме.
    print("Текущая сумма:", total)  # Показываем сумму сразу после каждого прибавления.

print("Квадрат числа N:", total)  # Итоговая сумма равна квадрату N.
