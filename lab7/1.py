# Задание 1. Реализовать сортировку пузырьком по возрастанию.
# Сравниваем соседние элементы и меняем их местами, если левый больше правого.
# После каждого прохода наибольший элемент оставшейся части оказывается справа на своём месте.

n = int(input("Введите количество элементов N, не меньше 0: "))  # Вводим размер массива; ноль означает пустой массив.

if n < 0:  # Проверяем, не ввели ли отрицательное количество элементов.
    print("Количество элементов не может быть отрицательным.")  # Объясняем, почему такой размер не подходит.
else:  # Для допустимого размера вводим и сортируем массив.
    numbers = []  # Создаём пустой список для чисел.
    for i in range(n):  # По очереди вводим все N элементов.
        value = float(input(f"Введите элемент {i + 1}: "))  # Вводим очередное число, можно отрицательное или дробное.
        numbers.append(value)  # Добавляем число в конец массива.

    print("Исходный массив:", numbers)  # Показываем массив до сортировки.

    for i in range(n - 1):  # Выполняем не больше N-1 проходов по массиву.
        swapped = False  # В начале прохода ещё не было ни одного обмена.
        for j in range(n - 1 - i):  # Сравниваем соседей, не затрагивая уже отсортированную правую часть.
            if numbers[j] > numbers[j + 1]:  # Проверяем, стоит ли большее число перед меньшим.
                numbers[j], numbers[j + 1] = numbers[j + 1], numbers[j]  # Меняем соседние элементы местами.
                swapped = True  # Запоминаем, что в этом проходе был обмен.
        if not swapped:  # Если обменов не было, все элементы уже стоят в нужном порядке.
            break  # Завершаем сортировку раньше, не выполняя лишние проходы.

    print("Массив по возрастанию:", numbers)  # Выводим отсортированный массив.
