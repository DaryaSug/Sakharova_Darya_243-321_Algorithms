# Задание 1. Реализовать сортировку пузырьком по возрастанию.
# Сравниваем соседние элементы и меняем их местами, если левый больше правого.
# После каждого прохода наибольший элемент оставшейся части оказывается справа на своём месте.

n = int(input("Введите количество элементов N, не меньше 0: "))  

if n < 0:  
    print("Количество элементов не может быть отрицательным.") 
else:  
    numbers = []  
    for i in range(n):  # По очереди вводим все N элементов.
        value = float(input(f"Введите элемент {i + 1}: "))  
        numbers.append(value)  

    print("Исходный массив:", numbers)  

    for i in range(n - 1):  # Выполняем не больше N-1 проходов по массиву.
        swapped = False  # В начале прохода ещё не было ни одного обмена.
        for j in range(n - 1 - i):  # Сравниваем соседей, не затрагивая уже отсортированную правую часть.
            if numbers[j] > numbers[j + 1]:  # Проверяем, стоит ли большее число перед меньшим.
                numbers[j], numbers[j + 1] = numbers[j + 1], numbers[j]  
                swapped = True 
        if not swapped: 
            break 
    print("Массив по возрастанию:", numbers)  
