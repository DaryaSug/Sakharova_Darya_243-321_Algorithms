# Задание 1. Реализовать рекурсивный обход бинарного дерева.
# Строим дерево поиска: меньшие значения идут влево, большие и равные — вправо.
# Обход «левое поддерево — узел — правое поддерево» выводит значения такого дерева по возрастанию.

class Node:  # Описываем узел — один элемент дерева со ссылками на потомков.
    def __init__(self, value):  # Эта функция вызывается при создании нового узла.
        self.value = value  # Сохраняем значение в текущем узле; self обозначает сам этот узел.
        self.left = None  # Левого потомка пока нет; None означает отсутствие узла.
        self.right = None  # Правого потомка пока тоже нет.


def insert(root, value):  # Создаём функцию добавления значения в дерево поиска.
    if root is None:  # Если в этом месте дерева ещё нет узла, нужно создать новый.
        return Node(value)  # Создаём узел с заданным значением и возвращаем его.
    if value < root.value:  # Если новое значение меньше текущего, оно должно находиться слева.
        root.left = insert(root.left, value)  # Рекурсивно добавляем значение в левое поддерево.
    else:  # Большие значения и повторения текущего значения отправляем вправо.
        root.right = insert(root.right, value)  # Рекурсивно добавляем значение в правое поддерево.
    return root  # Возвращаем корень обновлённого поддерева.


def inorder_traversal(root):  # Создаём функцию симметричного обхода: слева — узел — справа.
    if root is None:  # Базовый случай: если узла нет, обходить здесь нечего.
        return  # Завершаем этот вызов функции.
    inorder_traversal(root.left)  # Сначала рекурсивно обходим всё левое поддерево.
    print(root.value)  # Затем выводим значение текущего узла.
    inorder_traversal(root.right)  # В конце рекурсивно обходим всё правое поддерево.


n = int(input("Введите количество элементов N, не меньше 0: "))  # Вводим число узлов; ноль означает пустое дерево.

if n < 0:  # Проверяем, не ввели ли отрицательное количество элементов.
    print("Количество элементов не может быть отрицательным.")  # Объясняем, почему такое количество не подходит.
else:  # Для допустимого количества строим дерево и выполняем обход.
    tree = None  # Пока дерево пустое и корневого узла нет.
    for i in range(n):  # По очереди вводим все значения для дерева.
        value = float(input(f"Введите элемент {i + 1}: "))  # Вводим очередное число, можно отрицательное или дробное.
        tree = insert(tree, value)  # Добавляем число в дерево и сохраняем его корень.

    if tree is None:  # Проверяем, осталось ли дерево пустым.
        print("Дерево пустое.")  # Сообщаем, что в дереве нет элементов для обхода.
    else:  # Если узлы есть, выводим результат обхода.
        print("Обход дерева по возрастанию:")  # Выводим подпись перед значениями узлов.
        inorder_traversal(tree)  # Запускаем рекурсивный обход, который печатает каждый узел один раз.
